import { http } from './http';

// Compatible with the existing LingoBridge UI; all persisted state comes from FastAPI.
export const api = {
  getLanguages: () => http.get('/languages'),
  getLanguageByCode: code => http.get(`/languages/${encodeURIComponent(code)}`),
  createLanguage: data => http.post('/admin/manage/languages', data),
  updateLanguage: (id, data) => http.patch(`/admin/manage/languages/${encodeURIComponent(id)}`, data),
  deleteLanguage: id => http.delete(`/admin/manage/languages/${encodeURIComponent(id)}`),
  getLevels: () => http.get('/levels'),
  getCourses: filters => http.get('/courses', { params: filters }),
  getModules: courseId => http.get(`/courses/${encodeURIComponent(courseId)}/modules`),
  getEnrolledCourses: () => http.get('/courses/enrolled/me'),
  enrollInCourse: courseId => http.post(`/courses/${encodeURIComponent(courseId)}/enroll`),
  getFlashcardStates: () => http.get('/flashcards'),
  setFlashcardState: (wordId,state) => http.put(`/flashcards/${encodeURIComponent(wordId)}`,{state}),
  getLessons: filters => http.get('/lessons', { params: filters }),
  getLessonById: (id, { includeAnswers = false } = {}) => http.get(`/lessons/${encodeURIComponent(id)}`, { params: { include_answers: includeAnswers } }),
  createLesson: data => http.post('/admin/manage/lessons', data),
  updateLesson: (id, data) => http.patch(`/admin/manage/lessons/${encodeURIComponent(id)}`, data),
  deleteLesson: id => http.delete(`/admin/manage/lessons/${encodeURIComponent(id)}`),
  addVocabularyItem: (lessonId, data) => http.post(`/admin/lessons/${encodeURIComponent(lessonId)}/vocabulary`, data),
  deleteVocabularyItem: (_lessonId, id) => http.delete(`/admin/manage/vocabulary/${encodeURIComponent(id)}`),
  addQuizQuestion: (lessonId, data) => http.post(`/admin/lessons/${encodeURIComponent(lessonId)}/questions`, data),
  editQuizQuestion: (qid,data) => http.put(`/admin/questions/${encodeURIComponent(qid)}`,data),
  deleteQuizQuestion: (_lessonId, id) => http.delete(`/admin/manage/questions/${encodeURIComponent(id)}`),
  submitQuiz: (lessonId, _userId, answers, attemptToken) => http.post(`/lessons/${encodeURIComponent(lessonId)}/submit`, { answers, attempt_token: attemptToken || null }),
  beginQuiz: lessonId => http.post(`/lessons/${encodeURIComponent(lessonId)}/quiz-session`),
  getStudentEnrollments: () => http.get('/enrollments'),
  enrollInLanguage: (_userId, languageId) => http.post('/enrollments', { language_id: languageId }),
  getStudentProgress: () => http.get('/progress'),
  getRecommendations: () => http.get('/recommendations'),
  submitLessonStart: id => http.post(`/lessons/${encodeURIComponent(id)}/start`),
  getActivity: () => http.get('/activity'),
  logActivity: minutes => http.post('/activity', { minutes }),
  getBookmarks: () => http.get('/bookmarks'),
  bookmark: id => http.post(`/bookmarks/${encodeURIComponent(id)}`),
  unbookmark: id => http.delete(`/bookmarks/${encodeURIComponent(id)}`),
  getAdminStats: () => http.get('/admin/stats'),
  getAllStudents: () => http.get('/admin/students'),
  getStudentsPage: params => http.get('/admin/students/page', { params }),
  updateStudent: (id, data) => http.patch(`/admin/students/${encodeURIComponent(id)}`, data),
  adminList: table => http.get(`/admin/manage/${encodeURIComponent(table)}`),
  adminCreate: (table, data) => http.post(`/admin/manage/${encodeURIComponent(table)}`, data),
  adminUpdate: (table, id, data) => http.patch(`/admin/manage/${encodeURIComponent(table)}/${encodeURIComponent(id)}`, data),
  adminDelete: (table, id) => http.delete(`/admin/manage/${encodeURIComponent(table)}/${encodeURIComponent(id)}`),
  updateProfile: data => http.patch('/profile', data)
};
